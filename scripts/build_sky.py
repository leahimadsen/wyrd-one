"""Build static/sky-data.js: the real sky behind Odin's Eye.

    python scripts/build_sky.py path/to/d3-celestial/data

Stars to magnitude 5 and the Milky Way's outline come from d3-celestial (Olaf Frohn, BSD
licence), which takes its stars from XHIP, the extended Hipparcos compilation (Anderson &
Francis 2012), and its constellation lines from the IAU. Positions are J2000 right ascension
and declination in degrees, rounded to 0.01°."""
import json, os, sys

SRC = sys.argv[1] if len(sys.argv) > 1 else "data"
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "static", "sky-data.js")
LIMIT = 5.0
# the classical figures drawn in knotwork: their IAU stick figures go along, faint
LINES = ["Cyg", "Aql", "Lyr", "Dra", "Peg", "Leo", "Sco", "Cas", "UMi", "And"]

ra = lambda x: round(x % 360, 2)
stars = json.load(open(os.path.join(SRC, "stars.6.json")))["features"]
flat = []
for s in sorted(stars, key=lambda s: s["properties"]["mag"]):
    m = s["properties"]["mag"]
    if m > LIMIT: break
    x, y = s["geometry"]["coordinates"]
    flat += [ra(x), round(y, 2), round(m, 1)]

names = json.load(open(os.path.join(SRC, "starnames.json")))
byhip = {s["id"]: s["geometry"]["coordinates"] for s in stars}
NAMED = ["Sirius", "Betelgeuse", "Rigel", "Alnitak", "Alnilam", "Mintaka", "Castor", "Pollux", "Aldebaran", "Ain",
         "Polaris", "Dubhe", "Merak", "Phecda", "Megrez", "Alioth", "Mizar", "Alkaid", "Deneb", "Vega", "Altair", "Albireo",
         "Regulus", "Denebola", "Antares", "Markab", "Scheat", "Algenib", "Alpheratz", "Caph", "Thuban", "Eltanin", "Kochab"]
named = {}
for hip, v in names.items():
    if v.get("name") in NAMED and int(hip) in byhip:
        x, y = byhip[int(hip)]; named[v["name"]] = [ra(x), round(y, 2)]
# the Hyades' other bright stars (the V of the wolf's jaw), by Hipparcos number: γ, δ1, θ2 Tauri
for nm, hip in (("gamma Tau", 20205), ("delta1 Tau", 20455), ("theta2 Tau", 20894), ("epsilon Tau", 20889)):
    if hip in byhip: x, y = byhip[hip]; named[nm] = [ra(x), round(y, 2)]

lines = {}
for f in json.load(open(os.path.join(SRC, "constellations.lines.json")))["features"]:
    if f["id"] in LINES:
        lines[f["id"]] = [[v for p in seg for v in (ra(p[0]), round(p[1], 2))] for seg in f["geometry"]["coordinates"]]

# the Milky Way: its outline at five brightnesses, thinned to every few points
mw = []
for f in json.load(open(os.path.join(SRC, "mw.json")))["features"]:
    level = int(f["id"][-1]) if f["id"][-1].isdigit() else 1
    for poly in f["geometry"]["coordinates"]:
        for ring in poly:
            step = max(1, len(ring) // 28)
            pts = ring[::step]
            if len(ring) >= 40: mw.append([level, [v for p in pts for v in (round(p[0] % 360), round(p[1]))]])   # small knots dropped; whole degrees do for a glow

data = {"stars": flat, "named": named, "lines": lines, "mw": mw,
        "credit": "Stars: XHIP, the extended Hipparcos compilation (Anderson & Francis 2012), and the Milky Way's outline, by way of d3-celestial (Olaf Frohn, BSD licence); figure lines after the IAU."}
open(OUT, "w").write("/* generated by scripts/build_sky.py: do not edit by hand */\nwindow.WYRD_SKY_DATA = " + json.dumps(data, separators=(",", ":")) + ";\n")
print(f"{len(flat) // 3} stars, {len(named)} named, {len(lines)} figures' lines, {len(mw)} Milky Way rings -> {os.path.getsize(OUT) // 1024} KB")
