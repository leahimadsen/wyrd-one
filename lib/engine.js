/* ---- time ---- */
function julianDay(y, m, d, hUT){
  if (m <= 2){ y -= 1; m += 12; }
  const A = Math.floor(y / 100), B = 2 - A + Math.floor(A / 4);
  return Math.floor(365.25 * (y + 4716)) + Math.floor(30.6001 * (m + 1))
       + d + B - 1524.5 + hUT / 24;
}
const centuries = jd => (jd - 2451545.0) / 36525.0;

/* ---- ΔT · the series below are Terrestrial Time; the clock is Universal ----
   Every position function takes a UT Julian Day and converts internally.
   gmst / ascendant / midheaven stay on UT, which is correct for them.
   Espenak–Meeus polynomials. */
function deltaT(jd){
  const y = 2000 + (jd - 2451545.0) / 365.25;
  let t;
  if (y < 1900){ t = (y - 1860) / 100; return 7.62 + 57.37*t - 2.51*t*t; }
  if (y < 1920){ t = y - 1900; return -2.79 + 1.494119*t - 0.0598939*t*t + 0.0061966*t*t*t - 0.000197*t*t*t*t; }
  if (y < 1941){ t = y - 1920; return 21.20 + 0.84493*t - 0.076100*t*t + 0.0020936*t*t*t; }
  if (y < 1961){ t = y - 1950; return 29.07 + 0.407*t - t*t/233 + t*t*t/2547; }
  if (y < 1986){ t = y - 1975; return 45.45 + 1.067*t - t*t/260 - t*t*t/718; }
  if (y < 2005){ t = y - 2000; return 63.86 + 0.3345*t - 0.060374*t*t + 0.0017275*t*t*t
                                     + 0.000651814*t*t*t*t + 0.00002373599*t*t*t*t*t; }
  if (y < 2050){ t = y - 2000; return 62.92 + 0.32217*t + 0.005589*t*t; }
  t = (y - 1820) / 100; return -20 + 32*t*t;
}
const toTT = jd => jd + deltaT(jd) / 86400;

/* ---- general precession in longitude since J2000 ----
   The Sun and Moon series below are referred to the equinox OF DATE.
   The JPL Keplerian elements are referred to the J2000 equinox and must
   be brought forward, or the planets sit in a different sky from the
   luminaries — 25 arcmin apart for a 1970 birth, and the ×9 dharma
   transform multiplies that to over three degrees. Meeus 21.  */
function precJ2000(jd){
  const T = centuries(jd);
  return (5029.0966 * T + 1.11113 * T * T - 0.000006 * T * T * T) / 3600;
}
