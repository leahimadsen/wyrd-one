function helio(name, T){
  const e0 = ELEM[name];
  const a = e0[0] + e0[6] * T, e = e0[1] + e0[7] * T, I = e0[2] + e0[8] * T;
  const L = e0[3] + e0[9] * T, wbar = e0[4] + e0[10] * T, O = e0[5] + e0[11] * T;
  const w = wbar - O;
  let M = norm(L - wbar); if (M > 180) M -= 360;
  /* Kepler */
  let E = M + e * R2D * sin(M);
  for (let i = 0; i < 12; i++){
    const dM = M - (E - e * R2D * sin(E));
    E += dM / (1 - e * cos(E));
  }
  const xp = a * (cos(E) - e);
  const yp = a * Math.sqrt(1 - e * e) * sin(E);
  /* rotate to ecliptic */
  const cw = cos(w), sw = sin(w), cO = cos(O), sO = sin(O), cI = cos(I), sI = sin(I);
  return {
    x: (cw * cO - sw * sO * cI) * xp + (-sw * cO - cw * sO * cI) * yp,
    y: (cw * sO + sw * cO * cI) * xp + (-sw * sO + cw * cO * cI) * yp,
    z: (sw * sI) * xp + (cw * sI) * yp
  };
}

/* Geocentric apparent longitude, referred to the equinox of date.
   Three corrections the earlier build was missing:
     · UT → TT, so the elements are evaluated on the right clock
     · light-time, so the planet is placed where it was seen from, not
       where it stands now (up to 0.4′ for Mars, ~5.5h of travel for Pluto)
     · precession from J2000 to date, without which the planets sit in a
       different frame from the Sun and Moon
   Annual aberration (≤20.5″) is still not applied — that is ~3′ once the
   ×9 dharma transform has multiplied it, and is the largest term left. */
function planetLon(name, jdUT){
  const jd = toTT(jdUT);
  const T = centuries(jd);
  const e = helio("Earth", T);
  let p = helio(name, T), dx, dy, dz, r;
  for (let i = 0; i < 2; i++){
    dx = p.x - e.x; dy = p.y - e.y; dz = p.z - e.z;
    r = Math.sqrt(dx*dx + dy*dy + dz*dz);
    p = helio(name, centuries(jd - r / LIGHT_DAY));
  }
  dx = p.x - e.x; dy = p.y - e.y;
  return norm(Math.atan2(dy, dx) * R2D + precJ2000(jd));
}

