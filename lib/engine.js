/* ---- angles ---- */
function ascendant(jd, lat, lonE){
  const eps = obliquity(centuries(jd));
  const ramc = norm(gmst(jd) + lonE);
  let asc = Math.atan2(cos(ramc), -(sin(ramc) * cos(eps) + tan(lat) * sin(eps))) * R2D;
  return norm(asc);
}
function midheaven(jd, lonE){
  const eps = obliquity(centuries(jd));
  const ramc = norm(gmst(jd) + lonE);
  return norm(Math.atan2(sin(ramc), cos(ramc) * cos(eps)) * R2D);
}

