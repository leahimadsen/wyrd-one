function moonLon(jdUT){
  const jd = toTT(jdUT);
  const T = centuries(jd);
  const Lp = norm(218.3164477 + 481267.88123421 * T - 0.0015786 * T * T
                + T * T * T / 538841 - T * T * T * T / 65194000);
  const D  = norm(297.8501921 + 445267.1114034 * T - 0.0018819 * T * T
                + T * T * T / 545868 - T * T * T * T / 113065000);
  const M  = norm(357.5291092 + 35999.0502909 * T - 0.0001536 * T * T + T * T * T / 24490000);
  const Mp = norm(134.9633964 + 477198.8675055 * T + 0.0087414 * T * T
                + T * T * T / 69699 - T * T * T * T / 14712000);
  const F  = norm(93.2720950 + 483202.0175233 * T - 0.0036539 * T * T
                - T * T * T / 3526000 + T * T * T * T / 863310000);
  const E  = 1 - 0.002516 * T - 0.0000074 * T * T;

  let sum = 0;
  for (const [d, m, mp, f, c] of MOON_T){
    let e = 1;
    if (Math.abs(m) === 1) e = E;
    else if (Math.abs(m) === 2) e = E * E;
    sum += c * e * sin(d * D + m * M + mp * Mp + f * F);
  }
  /* additive terms */
  const A1 = norm(119.75 + 131.849 * T), A2 = norm(53.09 + 479264.290 * T);
  sum += 3958 * sin(A1) + 1962 * sin(Lp - F) + 318 * sin(A2);
  return norm(Lp + sum / 1e6);
}

